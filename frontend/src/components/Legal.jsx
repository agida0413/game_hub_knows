// 판 안내 — 지금 판 + 다음 판 안내 중 / 다음 판 미리 보기 / 이전 판
function EditionNote({ doc, ed }) {
  const { title, notice: Notice } = DOCS[doc]
  if (ed.shown === ed.current && ed.next) {
    return (
      <section className="legal-notice" aria-label="변경 예정 안내">
        <h3>변경 예정 안내 — {labelOf(ed.next)}부터 바뀝니다</h3>
        <Notice />
        <a href={`#/${doc}/${ed.next}`}>바뀌는 {title} 전문 보기</a>
      </section>
    )
  }
  if (ed.shown === ed.next) {
    return (
      <section className="legal-notice">
        <h3>{labelOf(ed.next)}부터 적용될 새 {title}입니다</h3>
        <p>그 전날까지는 지금 판({labelOf(ed.current)} 시행)이 적용됩니다.</p>
        <a href={`#/${doc}`}>지금 적용 중인 판 보기</a>
      </section>
    )
  }
  if (ed.shown !== ed.current) {
    const ids = EDITIONS[doc]
    const after = ids[ids.indexOf(ed.shown) + 1]
    return (
      <section className="legal-notice">
        <h3>이전 판입니다</h3>
        <p>{labelOf(ed.shown)}부터 {labelOf(dayBefore(after))}까지 적용된 {title}입니다.</p>
        <a href={`#/${doc}`}>지금 적용 중인 판 보기</a>
      </section>
    )
  }
  return null
}

function EditionList({ doc, ed }) {
  const ids = EDITIONS[doc]
  if (ids.length < 2) return null
  const tag = (id) => (id === ed.current ? '지금 적용' : id === ed.next ? '시행 예정' : '이전 판')
  return (
    <nav className="legal-editions" aria-label="판 목록">
      <span>판 목록</span>
      {[...ids].reverse().map((id) => (
        <a key={id} href={id === ed.current ? `#/${doc}` : `#/${doc}/${id}`} aria-current={id === ed.shown ? 'page' : undefined}>
          {labelOf(id)} 시행 ({tag(id)})
        </a>
      ))}
    </nav>
  )
}

